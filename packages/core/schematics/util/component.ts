import { getDecoratorMetadata, parseSourceFile } from '@angular/cdk/schematics'
import { Tree } from '@angular-devkit/schematics'
import { dirname, join, normalize } from '@angular-devkit/core'
import { insertImport } from '@schematics/angular/utility/ast-utils'
import { applyToUpdateRecorder } from '@schematics/angular/utility/change'
import * as ts from 'typescript'

import { getProject } from './project.js'

export class TemplateDescriptor {
    constructor(public templateProp: ts.PropertyAssignment,
        public templateUrlProp: ts.PropertyAssignment,
        public componentPath: string,
        public template: string) {
    }

    isInline(): boolean {
        return !!this.templateProp
    }
}

/** The component's `template` or `templateUrl` property and the template's text, read from the file if need be. */
export function getComponentTemplateDescriptor(host: Tree, componentPath: string): TemplateDescriptor {
    const compSource: ts.SourceFile = parseSourceFile(host, componentPath)
    const compMetadata: ts.Node = getDecoratorMetadata(compSource, 'Component', '@angular/core')[0]
    const templateProp = getMetadataProperty(compMetadata, 'template')
    const templateUrlProp = getMetadataProperty(compMetadata, 'templateUrl')

    const template: string = getComponentTemplate(host, componentPath, {
        templateProp,
        templateUrlProp
    })

    return new TemplateDescriptor(
        templateProp,
        templateUrlProp,
        componentPath,
        template
    )
}

/** Root component file names generated by the Angular CLI: `app.ts` since v20, `app.component.ts` before. */
const APP_COMPONENT_FILES = ['app.ts', 'app.component.ts']

/** The root component's file, the first of `APP_COMPONENT_FILES` that exists; `app.component.ts` when none does. */
export async function getAppComponentPath(tree: Tree, projectName: string): Promise<string> {
    const project = await getProject(tree, projectName)
    const candidates = APP_COMPONENT_FILES.map((file) => normalize(`${project.sourceRoot}/app/${file}`))
    return candidates.find((path) => tree.exists(path)) ?? candidates[candidates.length - 1]
}

/**
 * Adds the given symbols, imported from the given module, to the `imports` of a standalone component, unless it
 * imports them already. Returns `false` if it can't, when the component has no static metadata or `imports` array.
 */
export function addImportsToComponent(
    tree: Tree,
    componentPath: string,
    symbols: string[],
    moduleName: string
): boolean {
    const source = parseSourceFile(tree, componentPath)
    const metadata = getDecoratorMetadata(source, 'Component', '@angular/core')[0]
    if (!metadata || !ts.isObjectLiteralExpression(metadata)) {
        return false
    }

    const importsProp = getMetadataProperty(metadata, 'imports') as ts.PropertyAssignment | undefined
    if (importsProp && !ts.isArrayLiteralExpression(importsProp.initializer)) {
        return false
    }

    const elements = importsProp && ts.isArrayLiteralExpression(importsProp.initializer)
        ? importsProp.initializer.elements
        : undefined
    const existing = elements?.map((element) => element.getText()) ?? []
    const missing = symbols.filter((symbol) => !existing.includes(symbol))
    if (!missing.length) {
        return true
    }

    const recorder = tree.beginUpdate(componentPath)
    const list = missing.join(', ')
    const lastElement = elements?.[elements.length - 1]
    const lastProperty = metadata.properties[metadata.properties.length - 1]
    if (importsProp && lastElement) {
        recorder.insertRight(lastElement.getEnd(), `, ${list}`)
    } else if (importsProp) {
        recorder.insertRight(importsProp.initializer.getEnd() - 1, list)
    } else if (lastProperty) {
        const indent = /^\r?\n([ \t]*)/.exec(lastProperty.getFullText())?.[1]
        const separator = indent === undefined ? ' ' : `\n${indent}`
        recorder.insertRight(lastProperty.getEnd(), `,${separator}imports: [${list}]`)
    } else {
        recorder.insertRight(metadata.getEnd() - 1, `\n  imports: [${list}],\n`)
    }
    tree.commitUpdate(recorder)

    // One at a time, so each joins the import declaration the previous one added.
    for (const symbol of missing) {
        const updatedSource = parseSourceFile(tree, componentPath)
        const importRecorder = tree.beginUpdate(componentPath)
        applyToUpdateRecorder(importRecorder, [insertImport(updatedSource, componentPath, symbol, moduleName)])
        tree.commitUpdate(importRecorder)
    }

    return true
}

interface TemplateInfo {
    templateProp?: ts.PropertyAssignment
    templateUrlProp?: ts.PropertyAssignment
}

function getComponentTemplate(host: Tree, compPath: string, tmplInfo: TemplateInfo): string {
    let template = ''

    if (tmplInfo.templateProp) {
        template = (tmplInfo.templateProp.initializer as ts.StringLiteral).text
    } else if (tmplInfo.templateUrlProp) {
        const templateUrl = (tmplInfo.templateUrlProp.initializer as ts.StringLiteral).text
        const dir = dirname(normalize(compPath))
        const templatePath = join(dir, templateUrl)
        const buffer = host.read(templatePath)
        if (buffer) {
            template = buffer.toString()
        }
    }

    return template
}

function getMetadataProperty(metadata: ts.Node, propertyName: string): ts.PropertyAssignment {
    const properties = (metadata as ts.ObjectLiteralExpression).properties
    const property = properties
        .filter((prop) => prop.kind === ts.SyntaxKind.PropertyAssignment)
        .filter((prop: ts.PropertyAssignment) => {
            const name = prop.name
            switch (name.kind) {
                case ts.SyntaxKind.Identifier:
                    return (name as ts.Identifier).getText() === propertyName
                case ts.SyntaxKind.StringLiteral:
                    return (name as ts.StringLiteral).text === propertyName
            }

            return false
        })[0]

    return property as ts.PropertyAssignment
}
